/* assembler.c  --  "Assembler"
 * Input : file.bench (to find the flip-flops), file.ch (optimal order)
 * Output: out.v  (Verilog with the scan chain wired in the optimal order)
 *
 * SIMPLIFIED: it emits only the scan-chain part (one muxed-D scan flop per
 * DFF, chained SI <- previous Q). The full tool would also copy the
 * combinational logic from the scanchain.c output (file.v) into out.v.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv) {
    if (argc < 4) { fprintf(stderr, "usage: %s in.bench in.ch out.v\n", argv[0]); return 1; }
    char names[1024][64]; char dnet[1024][64]; int n = 0;
    FILE *f = fopen(argv[1], "r"); char line[512];
    while (fgets(line, sizeof line, f)) {            /* lines like:  G5 = DFF(G10) */
        char q[64], d[64];
        if (sscanf(line, " %63[^ =] = DFF(%63[^)])", q, d) == 2) {
            strcpy(names[n], q); strcpy(dnet[n], d); n++;
        }
    }
    fclose(f);

    int order[1024];
    f = fopen(argv[2], "r");
    for (int i = 0; i < n; i++) fscanf(f, "%d", &order[i]);
    fclose(f);

    FILE *o = fopen(argv[3], "w");
    fprintf(o, "// Generated by assembler.c -- scan chain in optimised order\n");
    fprintf(o, "module sdff(input CK, input SE, input DI, input SI, output reg Q);\n");
    fprintf(o, "  always @(posedge CK) Q <= SE ? SI : DI;   // muxed-D scan flop\n");
    fprintf(o, "endmodule\n\n");
    fprintf(o, "module scan_top(input CK, input SE, input scan_in, output scan_out);\n");
    for (int i = 0; i < n; i++) fprintf(o, "  wire %s, %s;\n", names[i], dnet[i]);
    for (int k = 0; k < n; k++) {
        int i = order[k];
        const char *si = (k == 0) ? "scan_in" : names[order[k-1]];
        fprintf(o, "  sdff u_%s (.CK(CK), .SE(SE), .DI(%s), .SI(%s), .Q(%s));\n",
                names[i], dnet[i], si, names[i]);
    }
    fprintf(o, "  assign scan_out = %s;\nendmodule\n", names[order[n-1]]);
    fclose(o);
    printf("assembler: wrote %s (chain: ", argv[3]);
    for (int k = 0; k < n; k++) printf("%s%s", names[order[k]], k < n-1 ? " -> " : "");
    printf(")\n");
    return 0;
}
